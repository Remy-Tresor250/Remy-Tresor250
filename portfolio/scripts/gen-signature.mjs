// Turns "Remy Tresor" in a script face into an SVG path for the scroll-drawn signature.
import opentype from 'opentype.js'
import { readFileSync, writeFileSync } from 'node:fs'
const buf = readFileSync('node_modules/@fontsource/mrs-saint-delafield/files/mrs-saint-delafield-latin-400-normal.woff')
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
// glyph by glyph: opentype's whole-string path emits NaNs for this face
const size = 200
const scale = size / font.unitsPerEm
const path = new opentype.Path()
let x = 0
for (const g of font.stringToGlyphs('Remy Tresor')) {
  const gp = g.getPath(0, 150, size)
  for (const c of gp.commands) {
    const t = { ...c }
    for (const k of ['x', 'x1', 'x2']) if (k in t) t[k] += x
    path.commands.push(t)
  }
  x += (Number.isFinite(g.advanceWidth) ? g.advanceWidth : font.unitsPerEm * 0.22) * scale
}
const bb = path.getBoundingBox()
const n = (v) => +v.toFixed(1)
const d = path.commands
  .map((c) => (c.type === 'Z' ? 'Z' : c.type === 'Q' ? `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}` : c.type === 'C' ? `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}` : `${c.type}${n(c.x)} ${n(c.y)}`))
  .join('')
if (d.includes('NaN')) throw new Error('NaN in signature path')
const view = [Math.floor(bb.x1) - 10, Math.floor(bb.y1) - 10, Math.ceil(bb.x2 - bb.x1) + 20, Math.ceil(bb.y2 - bb.y1) + 20]
writeFileSync('src/data/signature.ts', `// generated by scripts/gen-signature.mjs\nexport const signature = { viewBox: '${view.join(' ')}', d: '${d}' }\n`)
console.log('viewBox', view.join(' '), 'chars', d.length)
